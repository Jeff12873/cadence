// Pont entre l'interface (index.html) et le coffre Obsidian. Seules ces fonctions sont exposées,
// sous window.cadence. Sans elles (page ouverte dans un navigateur), l'interface fonctionne
// en mode autonome : chargement manuel du dossier, lecture seule, stockage dans le navigateur.

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('cadence', {
  config: () => ipcRenderer.invoke('config'),
  choisirCoffre: () => ipcRenderer.invoke('choisir-coffre'),
  reglerDonnees: (relatif) => ipcRenderer.invoke('regler-donnees', relatif),
  lireDonnees: () => ipcRenderer.invoke('lire-donnees'),
  ecrireDonnees: (donnees) => ipcRenderer.invoke('ecrire-donnees', donnees),
  lireTaches: () => ipcRenderer.invoke('lire-taches'),
  cocher: (nom, index, fait, mtime) => ipcRenderer.invoke('cocher', nom, index, fait, mtime),
  remplacerLigne: (nom, index, lien, mtime) => ipcRenderer.invoke('remplacer-ligne', nom, index, lien, mtime),
  planifier: (nom, valeur, mtime) => ipcRenderer.invoke('planifier', nom, valeur, mtime),
  planifierRecurrente: (nom, valeur, regle, mtime) => ipcRenderer.invoke('planifier-recurrente', nom, valeur, regle, mtime),
  validerOccurrence: (nom, jour, prochaine, mtime) => ipcRenderer.invoke('valider-occurrence', nom, jour, prochaine, mtime),
  annulerOccurrence: (nom, jour, ancien) => ipcRenderer.invoke('annuler-occurrence', nom, jour, ancien),
  creerTache: (tache) => ipcRenderer.invoke('creer-tache', tache),
  ajouterParent: (nom, parent, mtime) => ipcRenderer.invoke('ajouter-parent', nom, parent, mtime),
  ajouterBloquant: (nom, bloqueur, mtime) => ipcRenderer.invoke('ajouter-bloquant', nom, bloqueur, mtime),
  chercherNotes: (q) => ipcRenderer.invoke('chercher-notes', q),
  verifierMaj: () => ipcRenderer.invoke('verifier-maj'),
  copier: (texte) => ipcRenderer.invoke('copier', texte),
  modifierTache: (nom, champs, mtime) => ipcRenderer.invoke('modifier-tache', nom, champs, mtime),
  terminer: (nom, mtime) => ipcRenderer.invoke('terminer', nom, mtime),
  rouvrir: (nom, ancien) => ipcRenderer.invoke('rouvrir', nom, ancien),
  reglagesDaily: () => ipcRenderer.invoke('reglages-daily'),
  listerNotes: (dossier) => ipcRenderer.invoke('lister-notes', dossier),
  ecrireSection: (dossier, nom, section) => ipcRenderer.invoke('ecrire-section', dossier, nom, section),
  lierNote: (tache, note, mtime) => ipcRenderer.invoke('lier-note', tache, note, mtime),
  suivreNotes: (dossier) => ipcRenderer.invoke('suivre-notes', dossier),
  surChangementNotes: (fn) => ipcRenderer.on('notes-changees', () => fn()),
  lireNote: (dossier, nom) => ipcRenderer.invoke('lire-note', dossier, nom),
  ecrireNote: (dossier, nom, texte, mtime) => ipcRenderer.invoke('ecrire-note', dossier, nom, texte, mtime),
  renommerNote: (dossier, nom, nouveau) => ipcRenderer.invoke('renommer-note', dossier, nom, nouveau),
  supprimerTache: (nom, mtime) => ipcRenderer.invoke('supprimer-tache', nom, mtime),
  renommerTache: (nom, titre, mtime) => ipcRenderer.invoke('renommer-tache', nom, titre, mtime),
  meteo: (lat, lon) => ipcRenderer.invoke('meteo', lat, lon),
  meteoLieu: (nom) => ipcRenderer.invoke('meteo-lieu', nom),
  agendasGet: () => ipcRenderer.invoke('agendas-get'),
  agendasSet: (liste) => ipcRenderer.invoke('agendas-set', liste),
  agendasLire: (de, a) => ipcRenderer.invoke('agendas-lire', de, a),
  googleReglages: (id, secret, cal) => ipcRenderer.invoke('google-reglages', id, secret, cal),
  googleConnecter: () => ipcRenderer.invoke('google-connecter'),
  googleDeconnecter: () => ipcRenderer.invoke('google-deconnecter'),
  googleEnvoyer: (nom, ev, mtime) => ipcRenderer.invoke('google-envoyer', nom, ev, mtime),
  googleRetirer: (nom, id) => ipcRenderer.invoke('google-retirer', nom, id),
  googleBloc: (ev) => ipcRenderer.invoke('google-bloc', ev),
  googleAgendas: () => ipcRenderer.invoke('google-agendas'),
  googleCible: (id) => ipcRenderer.invoke('google-cible', id),
  agendaAfficher: (type, cle, afficher) => ipcRenderer.invoke('agenda-afficher', type, cle, afficher),
  agendaInfo: (id, info) => ipcRenderer.invoke('agenda-info', id, info),
  googleBlocRetirer: (id, cal) => ipcRenderer.invoke('google-bloc-retirer', id, cal),
  googleBlocsSimules: () => ipcRenderer.invoke('google-blocs-simules'),
  googleEmpreintes: () => ipcRenderer.invoke('google-empreintes'),
  googleLire: (de, a) => ipcRenderer.invoke('google-lire', de, a),
  googleModifier: (id, c, cal) => ipcRenderer.invoke('google-modifier', id, c, cal),
  googleCreer: (c, cal) => ipcRenderer.invoke('google-creer', c, cal),
  googleSupprimer: (id, cal) => ipcRenderer.invoke('google-supprimer', id, cal),
  ouvrirLien: (url) => ipcRenderer.invoke('ouvrir-lien', url),
  surChangementTaches: (fn) => ipcRenderer.on('taches-changees', () => fn()),
  surChangementDonnees: (fn) => ipcRenderer.on('donnees-changees', () => fn()),
});
